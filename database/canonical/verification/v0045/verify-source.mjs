import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFileSync,readdirSync,existsSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../../..');
const dir=path.join(root,'database/canonical/forward-candidates/family-membership-revocation');
const sqlPath=path.join(dir,'0045_family_membership_live_revocation.sql');
const rollbackPath=path.join(dir,'rollback_0045_family_membership_live_revocation.sql');
const manifestPath=path.join(dir,'manifest-0045-family-membership-revocation.json');
const hash=b=>createHash('sha256').update(b).digest('hex');
const sql=readFileSync(sqlPath),rollback=readFileSync(rollbackPath);
const manifest=JSON.parse(readFileSync(manifestPath,'utf8'));
assert.equal(hash(sql),manifest.sha256,'0045_SQL_SHA256_DRIFT');
assert.equal(hash(rollback),manifest.rollback_sha256,'0045_ROLLBACK_SHA256_DRIFT');
assert.equal(manifest.candidate,'0045');
assert.equal(manifest.formal_base.migrations,37);
for(const k of ['added_tables','added_columns','added_indexes','added_policies','added_roles','added_schemas'])assert.equal(manifest[k],0);
const source=sql.toString('utf8');
assert.match(source,/CREATE OR REPLACE FUNCTION learning\.can_read_sensitive/);
assert.match(source,/m\.family_id=p_family_id/);
assert.match(source,/m\.person_id=auth\.current_actor_person_id\(\)/);
assert.match(source,/m\.valid_from<=clock_timestamp\(\)/);
assert.match(source,/m\.valid_until IS NULL OR m\.valid_until>clock_timestamp\(\)/);
assert.match(source,/auth\.current_actor_person_id\(\)=p_subject_id/);
assert.match(source,/learning\.teacher_has_class_access/);
assert.doesNotMatch(source,/CREATE TABLE|ALTER TABLE|CREATE POLICY|CREATE ROLE|GRANT |REVOKE /);
assert.match(source,/S1_FUNCTION_SOURCE_DRIFT_REFUSED/);
assert.match(rollback.toString('utf8'),/S1_FUNCTION_SOURCE_DRIFT_REFUSED/);
const migrations=path.join(root,'database/canonical/migrations');
const files=readdirSync(migrations).filter(n=>n.endsWith('.sql')).sort();
assert.equal(files.length,37,'FORMAL_MIGRATION_COUNT_CHANGED');
assert.equal(files.at(-1),'0037_scoped_public_id_projection_read_audit.sql');
assert.equal(existsSync(path.join(migrations,'0045_family_membership_live_revocation.sql')),false);
