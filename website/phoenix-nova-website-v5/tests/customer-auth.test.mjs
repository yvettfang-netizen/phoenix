import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../lib/customer-auth.ts',import.meta.url),'utf8');
const js=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {readCustomerSession,handleCustomerAuth,authUnavailable,validAuthOrigin}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const origin='https://canonical.example.invalid';
const request=(action='session')=>new Request(origin+'/api/customer-auth/'+action);
test('Canonical customer identity is read-only and local D1 account mutations are retired',async()=>{
 const session={id:'synthetic-a',username:'synthetic',created_at:Date.now(),token_hash:'a'.repeat(64),valid_until:Date.now()+60000};
 let verified=0;
 const config={origin,async verifySession(){verified++;return session;},async recordAccess(){}};
 const r=await handleCustomerAuth(request(),config);
 assert.equal(r.status,200);assert.equal((await r.json()).user.id,session.id);
 assert.equal((await handleCustomerAuth(new Request(origin+'/api/customer-auth/register',{method:'POST'}),config)).status,503);
 assert.equal((await handleCustomerAuth(new Request(origin+'/api/customer-auth/login',{method:'POST'}),config)).status,503);
 assert.equal((await handleCustomerAuth(new Request(origin+'/api/customer-auth/recover',{method:'POST'}),config)).status,503);
 assert.equal(verified,1);
 assert.equal((await readCustomerSession(request(),{...config,async verifySession(){return {...session,valid_until:0};}})),null);
 assert.equal(authUnavailable().status,503);
 assert.equal(validAuthOrigin('https://canonical.example.invalid/path'),false);
});
